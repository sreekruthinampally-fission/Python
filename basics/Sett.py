colours = {"Blue", "Pink", "Orange", "Red", "Green", "5","7","2","3"}
print(colours)
numb = {"2", "3", "5", "7"}
print(numb)
print(colours.union(numb))
print(colours.intersection(numb))
print(colours.difference(numb))
print(colours.symmetric_difference(numb))
print(colours.issubset(numb))
print(colours.issuperset(numb))
print(colours.isdisjoint(numb))

